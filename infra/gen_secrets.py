"""Generate local secrets for the compose stack into infra/.env (never committed).

    python infra/gen_secrets.py           # creates infra/.env if it does not exist
    python infra/gen_secrets.py --force   # replaces it: existing encrypted data becomes UNREADABLE

Holds the PostgreSQL password and the AES-256 data key (ADR 0010). Later phases add more
secrets here (token signing key, per-device HMAC keys).
"""

from __future__ import annotations

import argparse
import base64
import secrets
from pathlib import Path

ENV_PATH = Path(__file__).resolve().parent / ".env"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="overwrite an existing infra/.env")
    args = parser.parse_args()

    if ENV_PATH.exists() and not args.force:
        print(f"{ENV_PATH} already exists; keeping it (use --force to replace).")
        return

    lines = [
        "# Generated by infra/gen_secrets.py. NEVER commit this file (safety invariant 7).",
        f"POSTGRES_PASSWORD={secrets.token_urlsafe(24)}",
        f"BORJ_DATA_KEY={base64.b64encode(secrets.token_bytes(32)).decode('ascii')}",
        "BORJ_DATA_KEY_ID=k1",
    ]
    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {ENV_PATH}")


if __name__ == "__main__":
    main()
