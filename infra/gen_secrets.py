"""Generate local secrets for the compose stack into .env (never committed).

    python infra/gen_secrets.py           # creates .env, or adds only the values it is missing
    python infra/gen_secrets.py --force   # regenerates everything: existing encrypted data becomes UNREADABLE

Holds (ADR 0010):
- POSTGRES_PASSWORD        database password
- BORJ_DATA_KEY(_ID)       AES-256-GCM key for patient payloads at rest
- BORJ_TOKEN_KEY           signing key for login tokens
- BORJ_STAFF_PINS          a random 6-digit demo PIN per synthetic staff member in seed/ward-W1.yaml
- FAMILY_PUBLISHER_TOKEN   bearer token the family publisher presents to family-gateway ingest
- FAMILY_DATA_KEY          AES-256-GCM key for what family-gateway stores (nurse-approved update text)
- BORJ_MQTT_USERS          broker accounts "user:password,...": server, sim, gw, node-B01...; the broker entrypoint
                           builds its password file from it (rules per account: infra/mosquitto/acl.conf)
- MQTT_PW_SERVER/_SIM/_GW  the same passwords for the compose services (a Raspberry Pi node uses its own entry)
- BORJ_DEVICE_KEYS         HMAC-SHA256 key ring for frame integrity (invariant 13): one key for the
                           simulator (sim-k1), one for the gateway (gw-k1), one per bedside node (node-B01...)
"""

from __future__ import annotations

import argparse
import base64
import re
import secrets
from pathlib import Path

INFRA = Path(__file__).resolve().parent
ENV_PATH = INFRA.parent / ".env"  # the repo root: where docker compose looks for it
LEGACY_ENV_PATH = INFRA / ".env"  # older checkouts kept it here; its values are carried over
SEED = INFRA.parent / "seed" / "ward-W1.yaml"
HEADER = "# Generated by infra/gen_secrets.py. NEVER commit this file (safety invariant 7)."


def staff_ids() -> list[str]:
    # Plain regex so this script needs no third-party packages (CI runs it before installing any).
    return re.findall(r"-\s*\{\s*id:\s*([A-Za-z0-9_-]+),\s*name:", SEED.read_text(encoding="utf-8"))


def bed_ids() -> list[str]:
    beds = SEED.read_text(encoding="utf-8").split("beds:", 1)[1]
    return re.findall(r"^\s+(B[0-9]+):", beds, flags=re.MULTILINE)


def device_keys() -> str:
    """'keyId:<base64 32-byte key>,...'. Key ids match what role A's signers use (sim-k1, gw-k1, node-{bed})."""
    ids = ["sim-k1", "gw-k1", *(f"node-{bed}" for bed in bed_ids())]
    return ",".join(f"{kid}:{base64.b64encode(secrets.token_bytes(32)).decode('ascii')}" for kid in ids)


def mqtt_accounts() -> dict[str, str]:
    """One random password per broker account. Names match infra/mosquitto/acl.conf."""
    users = ["server", "sim", "gw", *(f"node-{bed}" for bed in bed_ids())]
    return {user: secrets.token_urlsafe(18) for user in users}  # urlsafe: no ':' or ',' to break the list format


def fresh_values() -> dict[str, str]:
    pins = ",".join(f"{sid}:{secrets.randbelow(10**6):06d}" for sid in staff_ids())
    accounts = mqtt_accounts()
    return {
        "BORJ_MQTT_USERS": ",".join(f"{user}:{pw}" for user, pw in accounts.items()),
        "MQTT_PW_SERVER": accounts["server"],
        "MQTT_PW_SIM": accounts["sim"],
        "MQTT_PW_GW": accounts["gw"],
        "POSTGRES_PASSWORD": secrets.token_urlsafe(24),
        "BORJ_DATA_KEY": base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
        "BORJ_DATA_KEY_ID": "k1",
        "BORJ_TOKEN_KEY": base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
        "BORJ_STAFF_PINS": pins,
        "FAMILY_PUBLISHER_TOKEN": secrets.token_urlsafe(32),
        "FAMILY_DATA_KEY": base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
        "BORJ_DEVICE_KEYS": device_keys(),
    }


def read_env(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.lstrip().startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="regenerate every value in .env")
    args = parser.parse_args()

    if not ENV_PATH.exists() and LEGACY_ENV_PATH.exists() and not args.force:
        print(f"moving {LEGACY_ENV_PATH} to {ENV_PATH} (same values, so encrypted data stays readable)")
        ENV_PATH.write_text(LEGACY_ENV_PATH.read_text(encoding="utf-8"), encoding="utf-8")
    existing = {} if args.force or not ENV_PATH.exists() else read_env(ENV_PATH)
    generated = fresh_values()
    added = [k for k in generated if k not in existing]
    values = {**generated, **existing}  # never replace an existing value without --force

    ENV_PATH.write_text(HEADER + "\n" + "".join(f"{k}={v}\n" for k, v in values.items()), encoding="utf-8")
    print(f"{ENV_PATH}: {'added ' + ', '.join(added) if added else 'already complete'}")
    if "BORJ_MQTT_USERS" in added:
        print("Broker accounts for a Raspberry Pi bedside node: MQTT_USERNAME=node-B04, MQTT_PASSWORD=<its entry in "
              "BORJ_MQTT_USERS in .env>")
    if "BORJ_STAFF_PINS" in added:
        print("Demo staff PINs (synthetic staff, also stored in .env):")
        for pair in values["BORJ_STAFF_PINS"].split(","):
            print("  " + pair.replace(":", " -> "))


if __name__ == "__main__":
    main()
