"""Generate local secrets for the compose stack into infra/.env (never committed).

    python infra/gen_secrets.py           # creates infra/.env, or adds only the values it is missing
    python infra/gen_secrets.py --force   # regenerates everything: existing encrypted data becomes UNREADABLE

Holds (ADR 0010):
- POSTGRES_PASSWORD        database password
- BORJ_DATA_KEY(_ID)       AES-256-GCM key for patient payloads at rest
- BORJ_TOKEN_KEY           signing key for login tokens
- BORJ_STAFF_PINS          a random 6-digit demo PIN per synthetic staff member in seed/ward-W1.yaml
Later phases add per-device HMAC keys here.
"""

from __future__ import annotations

import argparse
import base64
import re
import secrets
from pathlib import Path

INFRA = Path(__file__).resolve().parent
ENV_PATH = INFRA / ".env"
SEED = INFRA.parent / "seed" / "ward-W1.yaml"
HEADER = "# Generated by infra/gen_secrets.py. NEVER commit this file (safety invariant 7)."


def staff_ids() -> list[str]:
    # Plain regex so this script needs no third-party packages (CI runs it before installing any).
    return re.findall(r"-\s*\{\s*id:\s*([A-Za-z0-9_-]+),\s*name:", SEED.read_text(encoding="utf-8"))


def fresh_values() -> dict[str, str]:
    pins = ",".join(f"{sid}:{secrets.randbelow(10**6):06d}" for sid in staff_ids())
    return {
        "POSTGRES_PASSWORD": secrets.token_urlsafe(24),
        "BORJ_DATA_KEY": base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
        "BORJ_DATA_KEY_ID": "k1",
        "BORJ_TOKEN_KEY": base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
        "BORJ_STAFF_PINS": pins,
    }


def read_env(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.lstrip().startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="regenerate every value in infra/.env")
    args = parser.parse_args()

    existing = {} if args.force or not ENV_PATH.exists() else read_env(ENV_PATH)
    generated = fresh_values()
    added = [k for k in generated if k not in existing]
    values = {**generated, **existing}  # never replace an existing value without --force

    ENV_PATH.write_text(HEADER + "\n" + "".join(f"{k}={v}\n" for k, v in values.items()), encoding="utf-8")
    print(f"{ENV_PATH}: {'added ' + ', '.join(added) if added else 'already complete'}")
    if "BORJ_STAFF_PINS" in added:
        print("Demo staff PINs (synthetic staff, also stored in infra/.env):")
        for pair in values["BORJ_STAFF_PINS"].split(","):
            print("  " + pair.replace(":", " -> "))


if __name__ == "__main__":
    main()
